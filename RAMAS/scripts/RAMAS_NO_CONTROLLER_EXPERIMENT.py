#!/usr/bin/env python3
"""RAMAS Stage-6 counterfactual: execute desired exposure without projection.

This is a ledger replay, not a new LLaMA run.  It reads the completed
Stage-6 archive's 03_DAILY_TRACE.csv and executes
memory_desired_exposure/no_memory_desired_exposure directly.  The archived
*_exposure field is never used because it is the controller-projected result.

Example:
  python3 RAMAS_NO_CONTROLLER_EXPERIMENT.py \
    --adaptive 20260908T055052711433762Z.tar.gz \
    --fixed 20260909T013716356200839Z.tar.gz \
    --output ramas_no_controller_results
"""
import argparse, csv, json, math, os, tarfile, zipfile

COST = 0.001
ANNUAL_DAYS = 365.25

def archive_members(path):
    if tarfile.is_tarfile(path):
        with tarfile.open(path) as z: return z.getnames()
    if zipfile.is_zipfile(path):
        with zipfile.ZipFile(path) as z: return z.namelist()
    raise ValueError(f"Not an archive: {path}")

def read_member(path, member):
    if tarfile.is_tarfile(path):
        with tarfile.open(path) as z:
            f = z.extractfile(member)
            if f is None: raise FileNotFoundError(member)
            return f.read()
    with zipfile.ZipFile(path) as z: return z.read(member)

def trace_member(path):
    names = archive_members(path)
    exact = [n for n in names if n.endswith("/03_DAILY_TRACE.csv")]
    if exact: return exact[0]
    candidates = [n for n in names if n.lower().endswith(".csv") and "trace" in n.lower()]
    if len(candidates) == 1: return candidates[0]
    raise ValueError(f"Could not identify 03_DAILY_TRACE.csv; candidates={candidates}")

def trace_rows(path):
    member = trace_member(path)
    text = read_member(path, member).decode("utf-8-sig")
    rows = list(csv.DictReader(text.splitlines()))
    if not rows: raise ValueError(f"Empty trace: {path}")
    return rows, member

def number(row, key):
    value = row.get(key, "")
    if value is None or value == "":
        raise ValueError(f"Missing {key} on row {row.get('index')}")
    return float(value)

def replay(rows, arm, start, end):
    prefix = arm + "_"
    needed = ["decision_date", "return_date", "asset_simple_return", prefix + "desired_exposure"]
    for key in needed:
        if key not in rows[0]:
            raise ValueError(f"Trace has no {key!r}; available columns={list(rows[0])}")

    # Initial p is imported once.  Thereafter p is generated by this
    # counterfactual's own executed exposure and BTC return.
    pkey = prefix + "pretrade_exposure"
    p = number(rows[0], pkey) if pkey in rows[0] else 0.0
    wealth = 1.0
    ledger = []
    for row in rows:
        d = str(row["decision_date"])[:10]
        rd = str(row["return_date"])[:10]
        x = number(row, prefix + "desired_exposure")
        asset = number(row, "asset_simple_return")
        if not 0.0 <= x <= 1.0: raise ValueError(f"{arm}: x={x} outside [0,1] on {d}")
        turnover = abs(x - p)
        fee_fraction = COST * turnover
        net = (1.0 - fee_fraction) * (1.0 + x * asset) - 1.0
        before = wealth
        wealth *= 1.0 + net
        # Drift after the return interval, assuming cash return is zero.
        p_next = x * (1.0 + asset) / (1.0 + x * asset)
        ledger.append({
            "decision_date": d, "return_date": rd,
            "hard_regime": row.get("hard_regime", ""),
            "asset_simple_return": asset,
            "desired_exposure_no_controller": x,
            "counterfactual_pretrade_exposure": p,
            "counterfactual_turnover": turnover,
            "fee_fraction": fee_fraction,
            "counterfactual_net_return": net,
            "wealth_before": before, "wealth_after": wealth,
            "original_controller_exposure": row.get(prefix + "exposure", ""),
            "action": row.get(prefix + "action", ""),
            "beta": row.get(prefix + "beta", ""),
            "retrieved_memory_count": row.get(prefix + "retrieved_memory_count", ""),
            "cited_memory_count": row.get(prefix + "cited_memory_count", ""),
            "projection_changes_selected_target": row.get(prefix + "projection_changes_selected_target", ""),
        })
        p = p_next

    selected = [r for r in ledger if start <= r["return_date"] <= end]
    if not selected: raise ValueError(f"No rows in {start}..{end}")
    returns = [r["counterfactual_net_return"] for r in selected]
    exposures = [r["desired_exposure_no_controller"] for r in selected]
    turnovers = [r["counterfactual_turnover"] for r in selected]
    n = len(returns)
    mean = sum(returns) / n
    sd = math.sqrt(sum((z - mean) ** 2 for z in returns) / (n - 1)) if n > 1 else 0.0
    downside = math.sqrt(sum(min(z, 0.0) ** 2 for z in returns) / n)
    losses = sorted((-z for z in returns), reverse=True)
    tail_mass = 0.05 * n
    k = math.floor(tail_mass)
    frac = tail_mass - k
    es95 = (sum(losses[:k]) + (frac * losses[k] if frac else 0.0)) / tail_mass
    opening = selected[0]["wealth_before"]
    value = opening; peak = opening; mdd = 0.0
    for z in returns:
        value *= 1.0 + z; peak = max(peak, value); mdd = max(mdd, 1.0 - value / peak)
    fees = sum(r["wealth_before"] * r["fee_fraction"] for r in selected)
    summary = {
        "rows": n, "first_return_date": selected[0]["return_date"],
        "last_return_date": selected[-1]["return_date"],
        "net_return_pct": (math.prod(1.0 + z for z in returns) - 1.0) * 100.0,
        "annualized_vol_pct": sd * math.sqrt(ANNUAL_DAYS) * 100.0,
        "sharpe_zero_rf": math.sqrt(ANNUAL_DAYS) * mean / sd if sd else None,
        "sortino_zero_target": math.sqrt(ANNUAL_DAYS) * mean / downside if downside else None,
        "max_drawdown_pct": mdd * 100.0,
        "es95_daily_loss_pct": es95 * 100.0,
        "mean_btc_exposure_pct": sum(exposures) / n * 100.0,
        "total_turnover": sum(turnovers),
        "mean_daily_turnover_pct": sum(turnovers) / n * 100.0,
        "fees_pct_evaluation_opening_capital": fees / opening * 100.0,
        "fees_per_10000_evaluation_opening_capital": fees / opening * 10000.0,
        "net_log_return": sum(math.log1p(z) for z in returns),
        "source_history_rows_replayed": len(ledger),
    }
    return summary, ledger

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--adaptive", help="Completed adaptive-trust archive")
    parser.add_argument("--fixed", help="Completed fixed-trust archive")
    parser.add_argument("--output", default="ramas_no_controller_results")
    parser.add_argument("--start", default="2022-01-01")
    parser.add_argument("--end", default="2025-05-28")
    parser.add_argument("--list-files", metavar="ARCHIVE")
    args = parser.parse_args()
    if args.list_files:
        print("\n".join(archive_members(args.list_files))); return
    if not args.adaptive and not args.fixed:
        parser.error("provide --adaptive and/or --fixed; use --list-files ARCHIVE first")
    os.makedirs(args.output, exist_ok=True)
    summaries, daily = {}, {}
    for setting, path in (("adaptive", args.adaptive), ("fixed", args.fixed)):
        if not path: continue
        source_rows, member = trace_rows(path)
        summaries[setting] = {"archive": os.path.abspath(path), "trace_member": member, "arms": {}}
        daily[setting] = {}
        for arm in ("memory", "no_memory"):
            summary, ledger = replay(source_rows, arm, args.start, args.end)
            summaries[setting]["arms"][arm] = summary
            daily[setting][arm] = ledger
    # Add an explicit paired contrast.  This prevents the common mistake of
    # comparing rounded values by eye and makes the ablation directly usable
    # in the report.  Differences are memory minus no-memory.
    for setting in summaries:
        mem_summary = summaries[setting]["arms"]["memory"]
        nomem_summary = summaries[setting]["arms"]["no_memory"]
        summaries[setting]["memory_minus_no_memory"] = {
            key: mem_summary[key] - nomem_summary[key]
            for key in mem_summary
            if isinstance(mem_summary[key], (int, float))
            and isinstance(nomem_summary.get(key), (int, float))
        }
    payload = {"contract": {"start": args.start, "end": args.end, "cost": COST,
                            "controller_bypassed": True,
                            "executed_field": "*_desired_exposure",
                            "final_controller_exposure_used": False},
               "results": summaries}
    with open(os.path.join(args.output, "no_controller_metrics.json"), "w", encoding="utf-8") as fp:
        json.dump(payload, fp, indent=2)
    for setting, arms in daily.items():
        for arm, rows_out in arms.items():
            name = f"{setting}_{arm}_no_controller_daily.csv"
            with open(os.path.join(args.output, name), "w", newline="", encoding="utf-8") as fp:
                writer = csv.DictWriter(fp, fieldnames=list(rows_out[0])); writer.writeheader(); writer.writerows(rows_out)
    print(json.dumps(payload, indent=2))

if __name__ == "__main__":
    main()
